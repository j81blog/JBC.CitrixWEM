<#
    .SYNOPSIS
        Escapes a string for safe use as a value inside an LDAP search filter.

    .DESCRIPTION
        Escapes the special characters defined by RFC 4515 so that a user-supplied value
        cannot break out of, or alter, an LDAP filter expression. The characters
        \ ( ) * and NUL are replaced with their \XX hex escape sequences.

        By default the asterisk (*) is escaped as well, so the value is matched literally.
        Use -PreserveWildcards when the caller intends the asterisk to act as a wildcard
        (for substring searches).

    .PARAMETER Value
        The raw string to escape.

    .PARAMETER PreserveWildcards
        When specified, the asterisk (*) is left intact so it functions as an LDAP wildcard.
        All other special characters are still escaped.

    .EXAMPLE
        ConvertTo-LdapFilterEscapedString -Value 'John (Admin)'
        Returns 'John \28Admin\29'.

    .EXAMPLE
        ConvertTo-LdapFilterEscapedString -Value 'Adm*' -PreserveWildcards
        Returns 'Adm*' (the wildcard is preserved, other specials are still escaped).

    .NOTES
        Function  : ConvertTo-LdapFilterEscapedString
        Author    : John Billekens Consultancy
        Copyright : Copyright (c) John Billekens Consultancy
        Version   : 1.0
#>
function ConvertTo-LdapFilterEscapedString {
    [CmdletBinding()]
    [OutputType([string])]
    param(
        [Parameter(Mandatory)]
        [AllowEmptyString()]
        [string]$Value,

        [Switch]$PreserveWildcards
    )

    if ([string]::IsNullOrEmpty($Value)) {
        return $Value
    }

    # Order matters: the backslash must be escaped first so that the escapes added for the
    # other characters are not themselves re-escaped.
    $escaped = $Value.Replace('\', '\5c')
    $escaped = $escaped.Replace('(', '\28')
    $escaped = $escaped.Replace(')', '\29')
    $escaped = $escaped.Replace("`0", '\00')

    if (-not $PreserveWildcards) {
        $escaped = $escaped.Replace('*', '\2a')
    }

    return $escaped
}

