<#
    .SYNOPSIS
        Retrieves information about the Active Directory domain using ADSI.
    .DESCRIPTION
        The `Get-AdsiADDomain` function retrieves information about the Active Directory domain using ADSI. The function returns a custom object with the following properties:
        - DistinguishedName: The distinguished name of the domain.
        - DNSRoot: The DNS root of the domain.
        - DirectoryServer: The name of the directory server.
        - NetBIOSName: The NetBIOS name of the domain.
    .PARAMETER Credential
        Specifies a user account that has permission to perform this action. The default value is an empty credential object.
    .PARAMETER Server
        Specifies the name of the server to connect to. If this parameter is not specified, the function connects to the local server.
    .PARAMETER Port
        Specifies the port number to use when connecting to the server. If this parameter is not specified, the function uses the default port number.
    .EXAMPLE
        PS C:\> Get-AdsiADDomain
        Retrieves information about the local Active Directory domain.
    .EXAMPLE
        PS C:\> Get-AdsiADDomain -Server "dc01.contoso.com" -Port 389 -Credential (Get-Credential)
        Retrieves information about the Active Directory domain on the server "dc01.contoso.com" using port 389 and the specified credentials.
    .NOTES
        Funtion   : Get-AdsiADDomain
        Author    : John Billekens
        Copyright : Copyright (c) John Billekens Consultancy
        Version   : 1.1
#>

function Get-AdsiADDomain {
    [CmdletBinding()]
    param(
        [Management.Automation.PSCredential]
        [Management.Automation.Credential()]$Credential = [Management.Automation.PSCredential]::Empty,

        [String]$Server,

        [Parameter()]
        [ValidateSet(0, 389, 636)]
        [Int]$Port = 389
    )
    Write-Verbose "Starting function : Get-AdsiADDomain"
    if ($Port -eq 0) { $Port = 389 }
    if (-not ($Credential -is [Management.Automation.PSCredential])) {
        $Credential = [Management.Automation.PSCredential]::Empty
    }
    # Session cache, keyed per server, port and account.
    if ($null -eq $Script:ADDomainCache) {
        $Script:ADDomainCache = @{}
    }
    $cacheKey = '{0}|{1}|{2}' -f "$Server".ToLower(), $Port, $Credential.UserName
    if ($Script:ADDomainCache.ContainsKey($cacheKey)) {
        Write-Verbose "Returning cached domain for '$cacheKey'"
        Write-Output $Script:ADDomainCache[$cacheKey]
        Write-Verbose "Ending function   : Get-AdsiADDomain"
        return
    }
    $domainOutput = @{
        DNSRoot           = $null
        DistinguishedName = $null
        DirectoryServer   = $null
        NetBIOSName       = $null
        Port              = $Port
        LDAPPath          = $null
    }
    $LDAPPath = "LDAP://"
    if (-not [String]::IsNullOrEmpty($Server)) {
        $LDAPPath += "$($Server):$($Port)/"
    }
    $domainOutput.LDAPPath = $LDAPPath
    $LDAPPath += "RootDSE"
    Write-Verbose "LDAPPath          : $LDAPPath"
    $root = $null
    $directoryEntry = $null
    try {
        if ($null -eq $Credential -or $Credential -eq [Management.Automation.PSCredential]::Empty) {
            $root = New-Object System.DirectoryServices.DirectoryEntry $LDAPPath
            Write-Verbose "Connecting        : Without credential"
        } else {
            $root = New-Object System.DirectoryServices.DirectoryEntry $LDAPPath, $($Credential.UserName), $($Credential.GetNetworkCredential().password)
            Write-Verbose "Connecting        : With credential"
        }
        try {
            # defaultNamingContext is the DC's own domain; rootDomainNamingContext would be the forest root.
            $domainOutput.DistinguishedName = $root | Select-Object -ExpandProperty defaultNamingContext
            $domainOutput.DNSRoot = $domainOutput.DistinguishedName -replace "\,(D|d)(C|c)\=", "." -replace "(D|d)(C|c)\=", $null
        } catch {
            Write-Verbose "Failed to retrieve domain DN and DNS root: $($_.Exception.Message)"
            $domainOutput.DistinguishedName = $null
            $domainOutput.DNSRoot = $null
        }
        try {
            $domainOutput.DirectoryServer = $root | Select-Object -ExpandProperty dnsHostName
        } catch {
            Write-Verbose "Failed to retrieve directory server hostname: $($_.Exception.Message)"
            $domainOutput.DirectoryServer = $null
        }

        try {
            $LDAPPath = "LDAP://$($domainOutput.DirectoryServer):$($Port)"
            if ($null -eq $Credential -or $Credential -eq [Management.Automation.PSCredential]::Empty) {
                $directoryEntry = New-Object System.DirectoryServices.DirectoryEntry $LDAPPath.TrimEnd('/')
            } else {
                $directoryEntry = New-Object System.DirectoryServices.DirectoryEntry $LDAPPath.TrimEnd('/'), $($Credential.UserName), $($Credential.GetNetworkCredential().password)
            }
            $domainOutput.LDAPPath = $LDAPPath
            $domainOutput.NetBIOSName = "$($directoryEntry.dc.ToString())".ToUpper()
        } catch {
            Write-Verbose "Failed to retrieve NetBIOS name: $($_.Exception.Message)"
            $domainOutput.NetBIOSName = $null
        }

        # The dc attribute is only the first DNS label; the real NetBIOS name is on the crossRef object.
        $partitionsEntry = $null
        $partitionsSearcher = $null
        try {
            $configNC = $root | Select-Object -ExpandProperty configurationNamingContext
            $partitionsPath = "LDAP://$($domainOutput.DirectoryServer):$($Port)/CN=Partitions,$($configNC)"
            if ($null -eq $Credential -or $Credential -eq [Management.Automation.PSCredential]::Empty) {
                $partitionsEntry = New-Object System.DirectoryServices.DirectoryEntry $partitionsPath
            } else {
                $partitionsEntry = New-Object System.DirectoryServices.DirectoryEntry $partitionsPath, $($Credential.UserName), $($Credential.GetNetworkCredential().password)
            }
            $partitionsSearcher = New-Object System.DirectoryServices.DirectorySearcher $partitionsEntry
            $partitionsSearcher.Filter = "(&(objectClass=crossRef)(nCName=$(ConvertTo-LdapFilterEscapedString -Value $domainOutput.DistinguishedName))(nETBIOSName=*))"
            $null = $partitionsSearcher.PropertiesToLoad.Add('netbiosname')
            $crossRef = $partitionsSearcher.FindOne()
            if ($null -ne $crossRef) {
                $domainOutput.NetBIOSName = "$($crossRef.Properties['netbiosname'][0])".ToUpper()
            } else {
                Write-Verbose "No crossRef found for '$($domainOutput.DistinguishedName)', keeping NetBIOS name '$($domainOutput.NetBIOSName)'"
            }
        } catch {
            Write-Verbose "Failed to read NetBIOS name from crossRef: $($_.Exception.Message)"
        } finally {
            if ($null -ne $partitionsSearcher) { $partitionsSearcher.Dispose() }
            if ($null -ne $partitionsEntry) { $partitionsEntry.Dispose() }
        }
        Write-Verbose "Domain DNS/NetBIOS: $($domainOutput.DNSRoot) / $($domainOutput.NetBIOSName)"

        $domainObject = [PSCustomObject]$domainOutput
        if (-not [String]::IsNullOrEmpty($domainOutput.DistinguishedName) -and -not [String]::IsNullOrEmpty($domainOutput.DirectoryServer)) {
            $Script:ADDomainCache[$cacheKey] = $domainObject
        }
        Write-Output $domainObject
    } finally {
        if ($null -ne $directoryEntry) {
            try {
                $directoryEntry.Dispose()
            } catch {
                Write-Verbose "Failed to dispose DirectoryEntry object: $($_.Exception.Message)"
            }
        }
        if ($null -ne $root) {
            try {
                $root.Dispose()
            } catch {
                Write-Verbose "Failed to dispose Root DirectoryEntry object: $($_.Exception.Message)"
            }
        }
    }
    Write-Verbose "Ending function   : Get-AdsiADDomain"
}

