<#
    .SYNOPSIS
        Retrieves an Active Directory user by identity or LDAP filter using ADSI.
    .DESCRIPTION
        The Get-AdsiADUser function retrieves an Active Directory user by name or LDAP filter. It searches for the user in the domain of the current user and returns the user's name, sAMAccountName, distinguishedName, userPrincipalName, and other properties.
    .PARAMETER Identity
        Specifies the identity (Name, sAMAccountName, or UserPrincipalName) of the Active Directory user to retrieve.
    .PARAMETER SearchLimit
        Specifies the maximum number of search results to return. Default is 200.
    .PARAMETER SearchBase
        Specifies the search base for the user search. If not specified, the search will be performed in the domain of the current user.
    .PARAMETER LDAPFilter
        Specifies an LDAP filter to narrow down the search results. This parameter is mandatory when using the 'LDAPFilter' parameter set.
    .PARAMETER Credential
        Specifies the credentials to use for the search. If not specified, the search will be performed with the credentials of the current user.
    .PARAMETER Server
        Specifies the domain controller to connect to for the search. If not specified, the search will be performed on the default domain controller.
    .PARAMETER Port
        Specifies the port number to use for the LDAP connection. Default is 389.
    .EXAMPLE
        Get-AdsiADUser -Identity "john.doe"

        Retrieves the user with the identity "john.doe" from Active Directory.
    .EXAMPLE
        Get-AdsiADUser -LDAPFilter "(department=IT)"

        Retrieves all users in the IT department using an LDAP filter.
    .EXAMPLE
        Get-AdsiADUser -Identity "john.doe" -Server "dc01.contoso.com" -Credential (Get-Credential)

        Retrieves the user "john.doe" from the specified domain controller using alternate credentials.
    .NOTES
        Function  : Get-AdsiADUser
        Author    : John Billekens Consultancy
        Copyright : Copyright (c) AppVentiX
        Version   : 1.0
        Requires  : Valid AppVentiX license
#>
function Get-AdsiADUser {
    [CmdletBinding(DefaultParameterSetName = 'Identity')]
    param (
        [Parameter(Mandatory = $true, ParameterSetName = 'Identity')]
        [Alias('Name')]
        [String]$Identity,

        [Parameter(ParameterSetName = 'Identity')]
        [Parameter(ParameterSetName = 'LDAPFilter')]
        [Int]$SearchLimit = 200,

        [Parameter(ParameterSetName = 'Identity')]
        [Parameter(ParameterSetName = 'LDAPFilter')]
        [String]$SearchBase,

        [Parameter(Mandatory = $true, ParameterSetName = 'LDAPFilter')]
        [String]$LDAPFilter,

        [Parameter(ParameterSetName = 'Identity')]
        [Parameter(ParameterSetName = 'LDAPFilter')]
        [Management.Automation.PSCredential]
        [Management.Automation.Credential()]$Credential = [Management.Automation.PSCredential]::Empty,

        [Parameter(ParameterSetName = 'Identity')]
        [Parameter(ParameterSetName = 'LDAPFilter')]
        [String]$Server,

        [Parameter(ParameterSetName = 'Identity')]
        [Parameter(ParameterSetName = 'LDAPFilter')]
        [ValidateSet(0, 389, 636)]
        [Int]$Port = 389,

        [Parameter(ParameterSetName = 'Identity')]
        [Parameter(ParameterSetName = 'LDAPFilter')]
        [String[]]$Properties = @()
    )

    Write-Verbose "Starting function : Get-AdsiADUser"
    $adsiADParams = $PSBoundParameters

    $adsiADParams.GetEnumerator() | ForEach-Object { Write-Verbose "Parameter         : $($_.Key) = $($_.Value)" }

    if (-not ($Credential -is [Management.Automation.PSCredential])) {
        $Credential = [Management.Automation.PSCredential]::Empty
    }
    $adsiADParams.Credential = $Credential

    $adsiADParams.ObjectType = "user"

    # Define default properties that are always retrieved for users
    $defaultProperties = @(
        "name",
        "sAMAccountName",
        "userPrincipalName",
        "distinguishedName",
        "displayName",
        "givenName",
        "sn",
        "mail",
        "userAccountControl",
        "department",
        "title",
        "company",
        "description",
        "objectSid"
    )

    # Merge default properties with any additional requested properties
    if ($Properties.Count -gt 0) {
        # Combine and get unique properties (case-insensitive)
        $allProperties = @($defaultProperties) + @($Properties) | Sort-Object -Unique
        Write-Verbose "Additional properties requested: $($Properties -join ', ')"
    } else {
        $allProperties = $defaultProperties
    }

    Write-Verbose "Total properties to retrieve: $($allProperties -join ', ')"
    $adsiADParams.Properties = $allProperties
    $result = @(Get-AdsiADObject @adsiADParams)
    Write-Verbose "Results received  : $($result.count)"

    if ($result.count -gt 0) {
        foreach ($user in $result) {
            $output = @{
                Name                 = $user.OtherProperties.name
                sAMAccountName       = $user.OtherProperties.sAMAccountName
                UserPrincipalName    = $user.OtherProperties.userPrincipalName
                DistinguishedName    = $user.OtherProperties.distinguishedName
                ObjectSid            = $user.OtherProperties.objectSid
                DisplayName          = $user.OtherProperties.displayName
                GivenName            = $user.OtherProperties.givenName
                Surname              = $user.OtherProperties.sn
                EmailAddress         = $user.OtherProperties.mail
                Enabled              = if ($user.OtherProperties.userAccountControl) {
                    -not ([int]$user.OtherProperties.userAccountControl -band 2)
                } else {
                    $null
                }
                Department           = $user.OtherProperties.department
                Title                = $user.OtherProperties.title
                Company              = $user.OtherProperties.company
                Description          = $user.OtherProperties.description
                OtherProperties      = $user.OtherProperties
            }
            Write-Output ([PSCustomObject]$output)
        }
    } else {
        if ($PSCmdlet.MyInvocation.BoundParameters.ContainsKey('Identity')) {
            Write-Warning "User with identity '$Identity' not found in Active Directory."
        } else {
            Write-Warning "User with LDAP filter '$LDAPFilter' not found in Active Directory."
        }
        Write-Output (@())
    }
    Write-Verbose "Ending function   : Get-AdsiADUser"
}

