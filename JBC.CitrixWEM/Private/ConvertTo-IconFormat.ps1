function ConvertTo-IconFormat {
    <#
    .SYNOPSIS
        Private helper function to convert an icon to ICO format with size adjustment.

    .DESCRIPTION
        This internal function converts a System.Drawing.Icon to ICO format bytes with
        high-quality rendering and transparency preservation. It creates a new ICO file
        at the specified size using high-quality bitmap rendering.

    .PARAMETER Icon
        The System.Drawing.Icon object to convert.

    .PARAMETER Size
        The desired width and height for the icon in pixels.

    .PARAMETER AsBase64
        If specified, returns the ICO data as a Base64 string. Otherwise returns byte array.

    .NOTES
        This is a private helper function used by Export-FileIcon.
    #>
    [CmdletBinding()]
    param (
        [Parameter(Mandatory = $true)]
        [System.Drawing.Icon]$Icon,

        [Parameter(Mandatory = $true)]
        [ValidateRange(16, 256)]
        [int]$Size,

        [Parameter()]
        [switch]$AsBase64
    )

    try {
        # Create high-quality bitmap
        $result = ConvertTo-HighQualityBitmap -Icon $Icon -Size $Size
        $graphics = $result.Graphics
        $bitmap = $result.Bitmap

        # Convert bitmap to icon
        $icoStream = New-Object System.IO.MemoryStream
        $iconHandle = $bitmap.GetHicon()
        $newIcon = [System.Drawing.Icon]::FromHandle($iconHandle)
        $newIcon.Save($icoStream)

        # Get the bytes
        $icoBytes = $icoStream.ToArray()

        # Cleanup
        $icoStream.Dispose()
        $graphics.Dispose()
        $bitmap.Dispose()
        $newIcon.Dispose()
        Remove-IconHandle -IconHandle $iconHandle

        # Return result
        if ($AsBase64) {
            return [Convert]::ToBase64String($icoBytes)
        } else {
            return $icoBytes
        }
    } catch {
        throw "Failed to convert to ICO format: $($_.Exception.Message)"
    }
}

